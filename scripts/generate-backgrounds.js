import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

// Make __dirname available in ESM
const __dirname = path.dirname(fileURLToPath(import.meta.url));

// Directory inside the repo where users will drop images
const PUBLIC_BACKGROUND_DIR = path.join(__dirname, '..', 'public', 'assets', 'backgrounds');
const OUT_DIR = path.join(__dirname, '..', 'src', 'generated');
const OUT_FILE = path.join(OUT_DIR, 'backgrounds.ts');

function main() {
  if (!fs.existsSync(PUBLIC_BACKGROUND_DIR)) {
    console.log('No backgrounds directory found at', PUBLIC_BACKGROUND_DIR);
    // ensure generated file exists with empty array
    writeGenerated([]);
    return;
  }

  const files = fs.readdirSync(PUBLIC_BACKGROUND_DIR).filter((f) => {
    const ext = path.extname(f).toLowerCase();
    return ['.jpg', '.jpeg', '.png', '.webp', '.svg'].includes(ext);
  });

  // natural (numeric-aware) sort for determinism and human-friendly ordering
  // so files like "background (1).jpg" .. "background (10).jpg" sort as expected
  files.sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }));

  writeGenerated(files);
}

function writeGenerated(files) {
  if (!fs.existsSync(OUT_DIR)) fs.mkdirSync(OUT_DIR, { recursive: true });
  const content = `// This file is generated by scripts/generate-backgrounds.js\n// Do not edit by hand.\n\nconst backgrounds = ${JSON.stringify(files, null, 2)} as string[];\n\nexport default backgrounds;\n`;
  fs.writeFileSync(OUT_FILE, content, 'utf8');
  console.log('Wrote', OUT_FILE, 'with', files.length, 'entries');
}

main();
